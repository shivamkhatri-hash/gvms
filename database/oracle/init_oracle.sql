-- GVMS - Oracle Database Initialization Script

-- ==================================================================================
-- 1. Core Schema Tables
-- ==================================================================================

-- Table 1: users
CREATE TABLE users (
    id VARCHAR2(36) DEFAULT LOWER(REGEXP_REPLACE(RAWTOHEX(SYS_GUID()), '([A-F0-9]{8})([A-F0-9]{4})([A-F0-9]{4})([A-F0-9]{4})([A-F0-9]{12})', '\1-\2-\3-\4-\5')) PRIMARY KEY,
    email VARCHAR2(255) UNIQUE NOT NULL,
    hashed_password VARCHAR2(255) NOT NULL,
    full_name VARCHAR2(255) NOT NULL,
    role VARCHAR2(50) DEFAULT 'viewer' NOT NULL, -- 'admin', 'researcher', 'viewer'
    is_active NUMBER(1) DEFAULT 1 NOT NULL,       -- Simulated BOOLEAN (0 = False, 1 = True)
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT check_users_is_active CHECK (is_active IN (0, 1))
);

-- Table 2: petroleum_data
CREATE TABLE petroleum_data (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY ON NULL PRIMARY KEY,
    sample_type VARCHAR2(100) NOT NULL,
    well_name VARCHAR2(100) NOT NULL,
    depth_from DOUBLE PRECISION NOT NULL,
    depth_interval DOUBLE PRECISION NOT NULL,
    toc DOUBLE PRECISION NOT NULL,
    s2 DOUBLE PRECISION NOT NULL,
    toc_classification VARCHAR2(50) NOT NULL,
    s2_classification VARCHAR2(50) NOT NULL,
    interpretation CLOB,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    uploaded_by VARCHAR2(36),
    CONSTRAINT fk_petroleum_uploaded_by FOREIGN KEY (uploaded_by) REFERENCES users(id) ON DELETE SET NULL
);

-- Table 3: upload_logs
CREATE TABLE upload_logs (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY ON NULL PRIMARY KEY,
    filename VARCHAR2(255) NOT NULL,
    file_size NUMBER(10) NOT NULL,
    total_rows NUMBER(10) NOT NULL,
    imported_rows NUMBER(10) NOT NULL,
    skipped_rows NUMBER(10) NOT NULL,
    error_summary CLOB,
    uploaded_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    uploaded_by VARCHAR2(36),
    CONSTRAINT fk_uploads_uploaded_by FOREIGN KEY (uploaded_by) REFERENCES users(id) ON DELETE SET NULL
);

-- Table 4: audit_logs
CREATE TABLE audit_logs (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY ON NULL PRIMARY KEY,
    user_id VARCHAR2(36),
    action VARCHAR2(100) NOT NULL,
    resource VARCHAR2(100) NOT NULL,
    details CLOB,
    ip_address VARCHAR2(45),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_audit_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
);

-- ==================================================================================
-- 2. Enterprise Dataset Registry & Versioning Tables
-- ==================================================================================

-- Table 5: dataset_registry
-- Stores configurable dataset definitions with dynamic column mappings and graph configs
CREATE TABLE dataset_registry (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY ON NULL PRIMARY KEY,
    name VARCHAR2(100) UNIQUE NOT NULL,
    display_name VARCHAR2(150) NOT NULL,
    sql_table_name VARCHAR2(100),
    module VARCHAR2(100) DEFAULT 'geochemistry',
    status VARCHAR2(50) DEFAULT 'active',
    version VARCHAR2(50) DEFAULT '1.0',
    description CLOB,
    mapping_config CLOB NOT NULL,
    graph_config CLOB NOT NULL,
    filter_config CLOB NOT NULL,
    required_columns VARCHAR2(1000) DEFAULT '[]' NOT NULL, -- Simulated string array via JSON
    primary_depth_column VARCHAR2(100),
    primary_well_column VARCHAR2(100),
    is_active NUMBER(1) DEFAULT 1 NOT NULL,                  -- Simulated BOOLEAN (0 = False, 1 = True)
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR2(36),
    CONSTRAINT check_dataset_is_active CHECK (is_active IN (0, 1)),
    CONSTRAINT check_dataset_mapping_json CHECK (mapping_config IS JSON),
    CONSTRAINT check_dataset_graph_json CHECK (graph_config IS JSON),
    CONSTRAINT check_dataset_filter_json CHECK (filter_config IS JSON),
    CONSTRAINT check_dataset_req_cols_json CHECK (required_columns IS JSON),
    CONSTRAINT fk_dataset_created_by FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL
);

-- Table 6: dataset_versions
-- Tracks versioned file uploads per registered dataset
CREATE TABLE dataset_versions (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY ON NULL PRIMARY KEY,
    dataset_id NUMBER(10) NOT NULL,
    version_number NUMBER(10) NOT NULL,
    filename VARCHAR2(255) NOT NULL,
    file_size NUMBER(10) DEFAULT 0 NOT NULL,
    total_rows NUMBER(10) DEFAULT 0 NOT NULL,
    imported_rows NUMBER(10) DEFAULT 0 NOT NULL,
    skipped_rows NUMBER(10) DEFAULT 0 NOT NULL,
    status VARCHAR2(50) DEFAULT 'pending' NOT NULL, -- 'pending', 'processing', 'completed', 'failed', 'rolled_back'
    is_active NUMBER(1) DEFAULT 1 NOT NULL,          -- Simulated BOOLEAN (0 = False, 1 = True)
    error_summary CLOB,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    uploaded_by VARCHAR2(36),
    CONSTRAINT fk_version_dataset FOREIGN KEY (dataset_id) REFERENCES dataset_registry(id) ON DELETE CASCADE,
    CONSTRAINT fk_version_uploaded_by FOREIGN KEY (uploaded_by) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT check_version_is_active CHECK (is_active IN (0, 1)),
    CONSTRAINT uq_dataset_version UNIQUE (dataset_id, version_number)
);

-- Table 7: generic_dataset_records
-- High-throughput JSON document store for arbitrary dataset rows
CREATE TABLE generic_dataset_records (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY ON NULL PRIMARY KEY,
    dataset_id NUMBER(10) NOT NULL,
    version_id NUMBER(10) NOT NULL,
    data CLOB NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_record_dataset FOREIGN KEY (dataset_id) REFERENCES dataset_registry(id) ON DELETE CASCADE,
    CONSTRAINT fk_record_version FOREIGN KEY (version_id) REFERENCES dataset_versions(id) ON DELETE CASCADE,
    CONSTRAINT check_record_data_json CHECK (data IS JSON)
);

-- Table 8: variable_registry
-- Stores variables definitions associated with datasets configuration
CREATE TABLE variable_registry (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY ON NULL PRIMARY KEY,
    dataset_id NUMBER(10) NOT NULL,
    name VARCHAR2(100) NOT NULL,
    display_name VARCHAR2(150) NOT NULL,
    sql_column_name VARCHAR2(100) NOT NULL,
    sql_data_type VARCHAR2(50) NOT NULL,
    display_unit VARCHAR2(50),
    is_numeric NUMBER(1) DEFAULT 1 NOT NULL,
    is_visible NUMBER(1) DEFAULT 1 NOT NULL,
    is_filterable NUMBER(1) DEFAULT 1 NOT NULL,
    chart_enabled NUMBER(1) DEFAULT 1 NOT NULL,
    kpi_enabled NUMBER(1) DEFAULT 1 NOT NULL,
    export_enabled NUMBER(1) DEFAULT 1 NOT NULL,
    description CLOB,
    validation_rule CLOB,
    category VARCHAR2(100),
    synonyms VARCHAR2(1000) DEFAULT '[]' NOT NULL, -- Simulated string array via JSON
    is_required NUMBER(1) DEFAULT 0 NOT NULL,
    is_nullable NUMBER(1) DEFAULT 1 NOT NULL,
    is_calculated NUMBER(1) DEFAULT 0 NOT NULL,
    formula VARCHAR2(255),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_variable_dataset FOREIGN KEY (dataset_id) REFERENCES dataset_registry(id) ON DELETE CASCADE,
    CONSTRAINT uq_var_dataset_column UNIQUE (dataset_id, sql_column_name),
    CONSTRAINT check_var_is_numeric CHECK (is_numeric IN (0, 1)),
    CONSTRAINT check_var_is_visible CHECK (is_visible IN (0, 1)),
    CONSTRAINT check_var_is_filterable CHECK (is_filterable IN (0, 1)),
    CONSTRAINT check_var_chart_enabled CHECK (chart_enabled IN (0, 1)),
    CONSTRAINT check_var_kpi_enabled CHECK (kpi_enabled IN (0, 1)),
    CONSTRAINT check_var_export_enabled CHECK (export_enabled IN (0, 1)),
    CONSTRAINT check_var_synonyms_json CHECK (synonyms IS JSON),
    CONSTRAINT check_var_is_required CHECK (is_required IN (0, 1)),
    CONSTRAINT check_var_is_nullable CHECK (is_nullable IN (0, 1)),
    CONSTRAINT check_var_is_calculated CHECK (is_calculated IN (0, 1))
);

-- Table 9: version_record_mapping
-- Maps dynamic record IDs in target tables to versions for rollbacks
CREATE TABLE version_record_mapping (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY ON NULL PRIMARY KEY,
    version_id NUMBER(10) NOT NULL,
    record_id NUMBER(10) NOT NULL,
    CONSTRAINT fk_mapping_version FOREIGN KEY (version_id) REFERENCES dataset_versions(id) ON DELETE CASCADE
);

